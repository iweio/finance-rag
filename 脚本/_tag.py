def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="校验全过后写回 xlsx")
    args = ap.parse_args()

    wb = openpyxl.load_workbook(XLSX)
    ws = wb.active
    cols = [c.value for c in ws[1]]
    i_d, i_t = cols.index("doc_id") + 1, cols.index("topic_tags") + 1
    ids = [ws.cell(r, i_d).value for r in range(2, ws.max_row + 1)]

    bad: list[str] = []
    extra = sorted(set(MAPPING) - set(ids))
    miss = sorted(set(ids) - set(MAPPING))
    if extra:
        bad.append(f"MAPPING 里有 {len(extra)} 个不在表里的 doc_id：{extra}")
    if miss:
        bad.append(f"表里有 {len(miss)} 份没回标：{miss}")

    for d, s in sorted(MAPPING.items()):
        tags = s.split(",")
        if not 1 <= len(tags) <= 3:
            bad.append(f"{d}: 标签数 {len(tags)}，要求 1~3")
        for t in tags:
            if t not in VOCAB:
                bad.append(f"{d}: 标签 `{t}` 不在词表里")
        if " " in s:
            bad.append(f"{d}: 标签串里有空格 —— 分隔符统一用半角逗号，不带空格")
        n = len(s.encode("utf-8"))
        if n > MAX_BYTES:
            bad.append(f"{d}: 标签串 {n} 字节 > Milvus max_length={MAX_BYTES}")

    if bad:
        print(f"### 校验未过 {len(bad)} 条（**不写**）")
        for b in bad:
            print("  - " + b)
        sys.exit(1)

    used: dict[str, list[str]] = {t: [] for t in VOCAB}
    for d, s in MAPPING.items():
        for t in s.split(","):
            used[t].append(d)
    unused = [t for t, v in used.items() if not v]
    widest = max(len(s.encode("utf-8")) for s in MAPPING.values())

    print(f"回标 {len(MAPPING)}/{len(ids)} 份，词表 {len(VOCAB)} 个标签")
    print(f"最长的标签串 {widest} 字节（上限 {MAX_BYTES}）")
    if unused:
        print(f"词表里没被用上的标签：{unused}")
    print()
    for t, v in sorted(used.items(), key=lambda kv: -len(kv[1])):
        print(f"  {len(v):3d}  {t}")

    # 词表 + 回标留痕，供复核
    with open(VOCAB_MD, "w", encoding="utf-8") as f:
        f.write("# topic_tags 词表与回标留痕\n\n")
        f.write("第 6 步产出。标签是**逐份手工判**的，不是关键词匹配——`证券` 一条规则就能命中\n")
        f.write("大半个库（证监会发的件标题里几乎都带「证券」），规则表会糊成一片。\n\n")
        f.write(f"分隔符：半角逗号 `,`，**不带空格**。每份 1~3 个标签。\n")
        f.write(f"字段类型 `VARCHAR({MAX_BYTES})`（[DB.md](../契约/DB.md) §3.1），当前最长 {widest} 字节。\n\n")
        f.write("`domain` 只有 5 个粗值（银行/证券/保险/外汇/综合），本轴补的是更细的**业务条线**，\n")
        f.write("两轴正交：`domain` 看「归谁管」，`topic_tags` 看「讲什么事」。\n\n")
        f.write("## 词表\n\n| 标签 | 命中 | 定义 |\n|---|---|---|\n")
        for t, desc in sorted(used.items(), key=lambda kv: -len(kv[1])):
            f.write(f"| `{t}` | {len(desc)} | {desc} |\n")
        f.write("\n> `债券市场` 的定义里含同业拆借、回购、做市、经纪、估值——这些同属**银行间市场业务**，\n")
